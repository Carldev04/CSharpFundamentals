namespace cSharpFundamentals._06_Operators
{
    public class ArithmeticOperators
    {
        public static void _Operators_()
        {
            //Operatori se koriste za izvođenje operacija nad varijablama i vrijednostima.
            //Na primjer operator zbrajanja (+)

            int sum = 100 + 50; //Rezultat je 150
            int sum2 = 250 + sum; //Rezultat je 400
            int sum3 = sum + sum2; //Rezultat je 800
            
            //Imamo 4 vrste operatora: aritmetički,operatori pridruživanja,operatori usporedbene i logički operatori.
            
            //Aritmetički operatori se koriste za izvođenje matematičkih operacija.
            
            /*
                +	Zbrajanje	Zbraja dvije vrijednosti	x + y
                -	Oduzimanje	Oduzima jednu vrijednost od druge	x - y
                *	Množenje	Množi dvije vrijednosti	x * y
                /	Dijeljenje	Dijeli jednu vrijednost drugom	x / y
                %	Modulo	Vraća ostatak pri dijeljenju	x % y
                ++	Inkrement	Povećava vrijednost varijable za 1	x++
                --	Dekrement	Smanjuje vrijednost varijable za 1	x--
             */
        }
    }
}